def dilate_font(
    font: dict[str, list[int]],
    dilate: int,
) -> dict[str, list[int]]:
    """
    Return a new font dict where every glyph has been grown by `dilate`
    pixels on all sides (up/down/left/right and diagonally) -- e.g. to use
    as a black outline layer drawn behind the normal glyph on backgrounds
    where plain text would be hard to read.

    Each glyph gains `dilate` extra columns on the left and right, and
    `dilate` extra rows above and below. bit 0 of the *output* still means
    "top row" -- but note the top row has shifted: what was row 0 in the
    input is now row `dilate` in the output, so when drawing the outline
    layer behind the original glyph, draw it at (x - dilate, y - dilate)
    relative to where you'd normally draw the glyph, so the two stay
    concentric.

    """
    set_cols = [c for cols in font.values() for c in cols if c]
    if not set_cols:
        raise ValueError("Cannot infer height: every glyph in this font is blank.")
    height = 1 + max(c.bit_length() - 1 for c in set_cols)

    new_height = height + 2 * dilate

    out: dict[str, list[int]] = {}
    for ch, cols in font.items():
        w = len(cols)
        new_w = w + 2 * dilate

        # place the original glyph, offset by `dilate` in both axes, onto a
        # padded boolean grid
        grid = [[False] * new_w for _ in range(new_height)]
        for x, c in enumerate(cols):
            for y in range(height):
                if c & (1 << y):
                    grid[y + dilate][x + dilate] = True

        if dilate == 0:
            out[ch] = list(cols)
            continue

        lit = [(y, x) for y in range(new_height) for x in range(new_w) if grid[y][x]]
        out_grid = [[False] * new_w for _ in range(new_height)]
        for (y, x) in lit:
            y0, y1 = max(0, y - dilate), min(new_height - 1, y + dilate)
            x0, x1 = max(0, x - dilate), min(new_w - 1, x + dilate)
            for ny in range(y0, y1 + 1):
                row = out_grid[ny]
                for nx in range(x0, x1 + 1):
                    row[nx] = True

        out_cols = []
        for x in range(new_w):
            v = 0
            for y in range(new_height):
                if out_grid[y][x]:
                    v |= (1 << y)
            out_cols.append(v)
        out[ch] = out_cols

    return out

for key in list(FONT):
    FONT[key, 1] = dilate_font(FONT[key], 1)